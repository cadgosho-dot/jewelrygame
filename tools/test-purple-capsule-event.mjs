import assert from 'node:assert/strict';
import { createEventStateHelpers } from '../js/events/event-state-helpers.js';
const state = {playerName:'川原',game:{minutes:1141,day:400},inventory:{items:{purpleCapsule:2}},events:{},wellbeing:{hunger:7}};
const helper = createEventStateHelpers(()=>state,()=>{},()=>{},()=>{},v=>v,{});
helper.configureServices({canSpendHours:h=>state.game.minutes+h*60<=1320,spendHours:h=>{state.game.minutes+=h*60;state.wellbeing.hunger-=h;}});
assert.equal(typeof helper.beginPurpleCapsule,'function','capsule transaction must be available');
assert.deepEqual(helper.beginPurpleCapsule(),{ok:false,reason:'time'});
assert.equal(state.inventory.items.purpleCapsule,2);
assert.equal(state.game.minutes,1141);
state.game.minutes=1140;
assert.equal(helper.beginPurpleCapsule().ok,true);
assert.equal(state.inventory.items.purpleCapsule,1);
assert.equal(state.game.minutes,1140,'time passes at completion');
assert.equal(helper.beginPurpleCapsule().reason,'active');
assert.equal(state.inventory.items.purpleCapsule,1);
assert.equal(helper.purpleCapsuleSnapshot().event.active,true);
assert.equal(helper.finishPurpleCapsule().ok,true);
assert.equal(state.game.minutes,1320);
assert.equal(state.wellbeing.hunger,4);
helper.finishPurpleCapsule();
assert.equal(state.game.minutes,1320,'completion is idempotent');
state.inventory.items.purpleCapsule=0;state.game.minutes=540;
assert.equal(helper.beginPurpleCapsule().reason,'item');
console.log('Purple capsule transaction: PASS');
