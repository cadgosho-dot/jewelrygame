function isRecord(value) {
  return Boolean(value) && typeof value === 'object' && !Array.isArray(value);
}

function merge(base, saved) {
  if (!isRecord(base)) return structuredClone(saved === undefined ? base : saved);
  if (!isRecord(saved)) return structuredClone(base);
  const out = structuredClone(base);
  for (const [key, value] of Object.entries(saved)) {
    if (!Object.prototype.hasOwnProperty.call(out, key)) {
      out[key] = structuredClone(value);
      continue;
    }
    const current = out[key];
    if (Array.isArray(current)) {
      if (Array.isArray(value)) out[key] = structuredClone(value);
      continue;
    }
    if (isRecord(current)) {
      if (isRecord(value)) out[key] = merge(current, value);
      continue;
    }
    out[key] = value;
  }
  return out;
}

function versionBefore(value, target) {
  const parse = (input) => String(input || '0').split('.').map((part) => Math.max(0, Number.parseInt(part, 10) || 0));
  const a = parse(value);
  const b = parse(target);
  const length = Math.max(a.length, b.length);
  for (let index = 0; index < length; index += 1) {
    const left = a[index] || 0;
    const right = b[index] || 0;
    if (left !== right) return left < right;
  }
  return false;
}

function strictLegacyQuantity(value) {
  // true / falseは発見済み・表示済みなどのフラグであり、所持数として扱わない。
  if (typeof value === 'boolean' || value === null || value === '') return 0;
  const quantity = Number(value);
  return Number.isFinite(quantity) ? Math.max(0, Math.floor(quantity)) : 0;
}

function legacyInventoryRowQuantity(row) {
  if (!row || typeof row !== 'object') return 0;
  // 数量が明示された旧データだけを移行する。
  // 数量項目がない行は商品一覧・発見記録の可能性があるため、1個へ変換しない。
  for (const key of ['qty', 'quantity', 'count', 'amount', 'owned']) {
    if (!Object.prototype.hasOwnProperty.call(row, key)) continue;
    return strictLegacyQuantity(row[key]);
  }
  return 0;
}

