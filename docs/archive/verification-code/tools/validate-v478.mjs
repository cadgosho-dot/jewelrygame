import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { VERSION } from '../js/game-data.js';
const here=path.dirname(fileURLToPath(import.meta.url)); const root=path.resolve(here,'..');
const app=fs.readFileSync(path.join(root,'js/app.js'),'utf8'); const css=fs.readFileSync(path.join(root,'styles.css'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8'); const indexHtml=fs.readFileSync(path.join(root,'index.html'),'utf8'); const gameHtml=fs.readFileSync(path.join(root,'game.html'),'utf8');
const assert=(c,m)=>{if(!c)throw new Error(m)};
assert(VERSION==='0.10.478','VERSIONが0.10.478ではありません');
assert(sw.includes("const VERSION = '0.10.478'"),'Service Workerが0.10.478ではありません');
assert(sw.includes('./js/daily-gems.js?v=0.10.478'),'Service Workerの日替わり宝石読込番号が古いままです');
assert(indexHtml.includes('game.html?v=0.10.478'),'index.htmlの読込番号が古いままです');
assert(gameHtml.includes('styles.css?v=0.10.478'),'game.htmlのCSS読込番号が古いままです');
assert(gameHtml.includes('js/app.js?v=0.10.478'),'game.htmlのapp.js読込番号が古いままです');
assert(app.includes("./daily-gems.js?v=0.10.478"),'app.jsの日替わり宝石読込番号が古いままです');
assert(app.includes('class="meal-eating-center"'),'食事内容の中央配置ラッパーがありません');
for(const marker of ['body[data-screen="meal"] .meal-eating-center{','place-items:center!important','align-content:center!important','justify-content:center!important','body[data-screen="meal"] .meal-eating-center > strong{']) assert(css.includes(marker),`食事中央配置CSSが不足しています: ${marker}`);
for(const marker of ['.tool-guide-toc summary,','.tool-guide-toc a:visited,','color:var(--text)!important','.tool-guide-toc summary::marker,']) assert(css.includes(marker),`目次文字色CSSが不足しています: ${marker}`);
assert(app.includes('data-action="meal-eating-finish"'),'食事画面タップ終了処理が失われています');
console.log('v0.10.478 食事中央配置・目次文字色検査: OK');
