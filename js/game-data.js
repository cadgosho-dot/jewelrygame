export function roundThousand(value) {
  return Math.max(1000, Math.round(Number(value || 0) / 1000) * 1000);
}

export function roundHundred(value) {
  return Math.max(100, Math.round(Number(value || 0) / 100) * 100);
}

export function roughSalePrice(gemId) {
  const gem = GEMS[gemId];
  return gem ? roundThousand((gem.roughPrice ?? gem.price) * 0.35) : 0;
}

export function looseCutPriceMultiplier(gemId, shapeId) {
  if (!GEMS[gemId]) return 1;
  const resolvedShape = looseShapeIdsForGem(gemId).includes(shapeId) ? shapeId : defaultLooseShapeForGem(gemId);
  if (CABOCHON_ONLY_GEMS.has(gemId)) return CABOCHON_GEM_PRICE_MULTIPLIERS[resolvedShape] || 1;
  return LOOSE_CUT_PRICE_MULTIPLIERS[resolvedShape] || 1;
}

export function loosePurchasePrice(gemId, shapeId) {
  const gem = GEMS[gemId];
  if (!gem) return 0;
  const rankMultiplier = LOOSE_RANK_PRICE_MULTIPLIERS[gem.looseRank] || 1;
  return roundHundred(gem.price * rankMultiplier * looseCutPriceMultiplier(gemId, shapeId));
}

export function looseSalePrice(gemId, shapeId) {
  const purchasePrice = loosePurchasePrice(gemId, shapeId);
  return purchasePrice ? roundHundred(purchasePrice * 0.55) : 0;
}

export function recommendedPrice({ item, gem, looseShape, metal, quality, useLoose = true }) {
  // 自店舗で販売する場合は、制作・接客・店舗運営分の利益を確保する。
  // シルバーは地金単価が低いため、プラチナ・ゴールドより少し高い倍率を適用する。
  // さらにルース付きの商品は、石選び・石合わせ・石留めの価値を反映して倍率を0.1だけ上げる。
  const standardMultiplier = quality === 'premium' ? 2.8 : quality === 'good' ? 2.5 : 2.2;
  const silverMultiplier = quality === 'premium' ? 3.1 : quality === 'good' ? 2.8 : 2.5;
  const baseMultiplier = metal === 'silver' ? silverMultiplier : standardMultiplier;
  const cost = productionCost({ item, gem, looseShape, metal, useLoose });
  const basePrice = roundThousand(cost * baseMultiplier);
  if (useLoose === false) return basePrice;
  // 1,000円単位の丸めで+0.1の差が消える低価格品も、ルース付きの利益差を最低1,000円は残す。
  return Math.max(basePrice + 1000, roundThousand(cost * (baseMultiplier + 0.1)));
}

export function productionCost({ item, gem, looseShape, metal, useLoose = true }) {
  const itemData = ITEMS[item] || ITEMS.ring;
  const metalData = METALS[metal] || METALS.silver;
  const looseQuantity = useLoose === false ? 0 : Math.max(1, Number(itemData.looseQuantity) || 1);
  const metalWeight = Math.max(0.1, Number(itemData.metalWeight) || 1);
  const looseCost = looseQuantity > 0 ? loosePurchasePrice(gem, looseShape) * looseQuantity : 0;
  return Math.round(looseCost + (metalData.price * metalWeight));
}

