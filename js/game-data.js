      lastCheckedDate: /^\d{4}-\d{2}-\d{2}$/.test(String(saved.lastCheckedDate || '')) ? String(saved.lastCheckedDate) : '',
      totalTriggered: Math.max(0, Math.floor(Number(saved.totalTriggered) || 0)),
